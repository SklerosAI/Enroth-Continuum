#pragma once

#include <array>
#include <cstdint>
#include <functional>
#include <optional>
#include <utility>
#include <vector>

#include "Engine/MM6/MM6ChestCallerAdapter.h"
#include "Engine/Objects/Chest.h"

namespace mm6 {

// A source-order plan over item IDs only. The 28-byte item fields, artifact
// ownership, grid placement and live state commit remain separate owners.
struct ChestOuterInput {
    GameTitle title = GameTitle::MM7;
    MapTreasureLevel mapTreasureLevel = static_cast<MapTreasureLevel>(-1);
    std::uint32_t rngState = 0;
    std::array<std::array<int, 140>, 20> itemIds = {};
};

struct ChestOuterReward {
    int itemId = 0;
    std::uint32_t nextRngState = 0;
};

// Source-order decisions are needed by a later raw-item transaction. A
// callback's nth result corresponds to the nth AnyItem/DirectArtifact entry.
struct ChestOuterSelection {
    int chestIndex = 0;
    int slotIndex = 0;
    ChestRewardSource source = ChestRewardSource::Empty;
    ItemTreasureLevel tier = ITEM_TREASURE_LEVEL_1;
    int itemId = 0;
    int goldAmount = 0;
};

using ChestOuterPicker = std::function<std::optional<ChestOuterReward>(
    ItemTreasureLevel tier, std::uint32_t rngState)>;

struct ChestOuterResult {
    std::array<std::array<int, 140>, 20> itemIds = {};
    // Only amounts generated by this pass; existing item fields are not read.
    std::array<std::array<int, 140>, 20> generatedGoldAmounts = {};
    std::uint32_t nextRngState = 0;
    int markersVisited = 0;
    int rewardsGenerated = 0;
    int emptyAttempts = 0;
    std::vector<ChestOuterSelection> selections;
};

// Reproduces the accepted original outer loop's order and first-attempt
// probability carry. Callbacks stage the separate ANY and direct-artifact
// picker results and must return a title-valid item ID and next RNG state.
inline std::optional<ChestOuterResult> stageChestOuterIds(
    const ChestOuterInput &input, const ChestOuterPicker &pickAny,
    const ChestOuterPicker &pickDirectArtifact) {
    if (input.title != GameTitle::MM6)
        return std::nullopt;
    const int mapLevel = std::to_underlying(input.mapTreasureLevel);
    if (mapLevel < 0 || mapLevel > 6)
        return std::nullopt;
    for (const auto &chest : input.itemIds)
        for (int id : chest)
            if (id < -7 || id > 580)
                return std::nullopt;

    ChestOuterResult result;
    result.itemIds = input.itemIds;
    result.nextRngState = input.rngState;
    auto draw = [&result]() { return nextChestRandom15(result.nextRngState); };
    int carriedProbability = draw() % 100;  // Even marker-free maps consume this draw.

    for (int chestIndex = 0; chestIndex < 20; ++chestIndex) {
        auto &chest = result.itemIds[chestIndex];
        for (int markerSlot = 0; markerSlot < 140; ++markerSlot) {
            const int marker = chest[markerSlot];
            if (marker >= 0)
                continue;
            ++result.markersVisited;
            const int attemptCount = 1 + draw() % 5;
            const auto range = chestTreasureLevelRangeForMarker(marker, input.mapTreasureLevel);
            if (!range)
                return std::nullopt;
            const int low = std::to_underlying(range->front());
            const int high = std::to_underlying(range->back());
            const auto tier = static_cast<ItemTreasureLevel>(low + draw() % (high - low + 1));
            if (tier == ITEM_TREASURE_LEVEL_7) {
                if (!pickDirectArtifact)
                    return std::nullopt;
                const auto reward = pickDirectArtifact(tier, result.nextRngState);
                // A bounded policy may have no eligible artifact and clear
                // the marker, as the original picker does on no candidate.
                if (!reward || (reward->itemId != 0 && !mm6ChestItemId(input.title, reward->itemId)))
                    return std::nullopt;
                chest[markerSlot] = reward->itemId;
                result.nextRngState = reward->nextRngState;
                result.selections.push_back({chestIndex, markerSlot, ChestRewardSource::DirectArtifact,
                                             tier, reward->itemId, 0});
                if (reward->itemId != 0)
                    ++result.rewardsGenerated;
                continue;
            }

            int targetSlot = markerSlot;
            for (int attempt = 0; attempt < attemptCount; ++attempt) {
                if (attempt > 0) {
                    targetSlot = 0;
                    while (targetSlot < 140 && chest[targetSlot] != 0)
                        ++targetSlot;
                    if (targetSlot == 140)
                        break;  // No additional slot: no probability draw.
                    carriedProbability = draw() % 100;
                }
                const auto source = chestRewardSource(input.title, tier, carriedProbability);
                if (!source)
                    return std::nullopt;
                if (*source == ChestRewardSource::Empty) {
                    chest[targetSlot] = 0;
                    ++result.emptyAttempts;
                    result.selections.push_back({chestIndex, targetSlot, *source, tier, 0, 0});
                    continue;
                }
                if (*source == ChestRewardSource::Gold) {
                    const auto gold = pickChestGold(input.title, tier, result.nextRngState);
                    if (!gold)
                        return std::nullopt;
                    chest[targetSlot] = std::to_underlying(gold->itemId);
                    result.generatedGoldAmounts[chestIndex][targetSlot] = gold->amount;
                    result.nextRngState = gold->nextRngState;
                    result.selections.push_back({chestIndex, targetSlot, *source, tier,
                                                 chest[targetSlot], gold->amount});
                } else {
                    if (!pickAny)
                        return std::nullopt;
                    const auto reward = pickAny(tier, result.nextRngState);
                    if (!reward || !mm6ChestItemId(input.title, reward->itemId))
                        return std::nullopt;
                    chest[targetSlot] = reward->itemId;
                    result.nextRngState = reward->nextRngState;
                    result.selections.push_back({chestIndex, targetSlot, *source, tier,
                                                 reward->itemId, 0});
                }
                ++result.rewardsGenerated;
            }
        }
    }
    return result;
}

}  // namespace mm6
